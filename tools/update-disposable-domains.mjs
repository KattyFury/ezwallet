// Refreshes functions/api/_disposableDomains.js from the community blocklist (CC0, public domain):
// https://github.com/disposable-email-domains/disposable-email-domains
// Run:  node tools/update-disposable-domains.mjs   → review the diff → commit.
import { writeFileSync } from 'node:fs'

const URL_ = 'https://raw.githubusercontent.com/disposable-email-domains/disposable-email-domains/main/disposable_email_blocklist.conf'
const MUST_NOT_BLOCK = ['gmail.com', 'yahoo.com', 'outlook.com', 'hotmail.com', 'icloud.com', 'proton.me', 'protonmail.com']

const text = await (await fetch(URL_)).text()
const domains = [...new Set(text.split('\n').map(s => s.trim().toLowerCase()).filter(s => s && !s.startsWith('#')))].sort()
if (domains.length < 1000) throw new Error(`only ${domains.length} domains - refusing to write a suspicious list`)
const bad = MUST_NOT_BLOCK.filter(d => domains.includes(d))
if (bad.length) throw new Error(`list would block real providers: ${bad.join(', ')}`)

writeFileSync(new URL('../functions/api/_disposableDomains.js', import.meta.url),
  `// GENERATED by tools/update-disposable-domains.mjs on ${new Date().toISOString().slice(0, 10)} - do not edit by hand.\n` +
  `// Source (CC0): github.com/disposable-email-domains/disposable-email-domains · ${domains.length} domains.\n` +
  `export const DISPOSABLE_DOMAINS = ${JSON.stringify(domains.join('\n'))}\n`)
console.log(`wrote ${domains.length} domains`)
